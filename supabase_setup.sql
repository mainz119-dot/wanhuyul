-- 자료실: 기존 family-photos 버킷의 resources/ 폴더 사용
drop policy if exists "family resources read" on storage.objects;
create policy "family resources read" on storage.objects for select to anon, authenticated using (bucket_id = 'family-photos' and name like 'resources/%');

drop policy if exists "family resources upload" on storage.objects;
create policy "family resources upload" on storage.objects for insert to anon, authenticated with check (bucket_id = 'family-photos' and name like 'resources/%');

drop policy if exists "family resources delete" on storage.objects;
create policy "family resources delete" on storage.objects for delete to anon, authenticated using (bucket_id = 'family-photos' and name like 'resources/%');
