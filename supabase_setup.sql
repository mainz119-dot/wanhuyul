-- 완후율: APK 전환을 고려한 일정/기념일 데이터 구조
-- 기존 데이터는 삭제하지 않습니다. Supabase SQL Editor에서 1회 실행

alter table public.schedule_items
  add column if not exists reminder_minutes integer not null default 0;

-- 기념일과 자동 생성된 일정의 연결 정보
alter table public.schedule_items
  add column if not exists source_type text,
  add column if not exists source_id bigint;

create table if not exists public.family_anniversaries (
  id bigint generated by default as identity primary key,
  type text not null default '⭐ 기타',
  name text not null,
  month smallint not null check (month between 1 and 12),
  day smallint not null check (day between 1 and 31),
  original_date date,
  created_by text not null,
  created_at timestamptz not null default now()
);

alter table public.family_anniversaries enable row level security;

drop policy if exists "family anniversaries read" on public.family_anniversaries;
create policy "family anniversaries read" on public.family_anniversaries for select to anon, authenticated using (true);

drop policy if exists "family anniversaries insert" on public.family_anniversaries;
create policy "family anniversaries insert" on public.family_anniversaries for insert to anon, authenticated with check (true);

drop policy if exists "family anniversaries delete" on public.family_anniversaries;
create policy "family anniversaries delete" on public.family_anniversaries for delete to anon, authenticated using (true);

